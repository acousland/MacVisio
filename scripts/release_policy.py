def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def load_json(path):
    path = Path(path)
    require(path.stat().st_size <= 1024 * 1024, 'JSON evidence exceeds 1 MiB')
    return json.loads(path.read_text())


def safe_local(root, name):
    require(isinstance(name, str) and name and '\\' not in name and '\x00' not in name, 'Invalid evidence path')
    relative = PurePosixPath(name)
    require(not relative.is_absolute() and '..' not in relative.parts, 'Evidence must stay within its directory')
    root = Path(root).resolve()
    result = root.joinpath(*relative.parts).resolve()
    require(result.is_relative_to(root) and result.is_file(), 'Evidence file missing or outside its directory')
    return result


def checked_attachment(root, reference):
    require(isinstance(reference, dict), 'Evidence reference must include path and sha256')
    path = safe_local(root, reference.get('path'))
    require(sha256(path) == reference.get('sha256'), 'Evidence digest mismatch')
    return path


def check_bundle_channel(info, channel):
    require(channel in {'stable', 'development'}, 'Unknown release channel')
    require(info.get('MacVisioReleaseChannel') == channel, 'Bundle release channel mismatch; rebuild before signing')
    if channel == 'stable':
        require(info.get('SUFeedURL') == STABLE_FEED, 'Bundle feed does not match release channel')
    else:
        version = info.get('CFBundleShortVersionString', '')
        require(re.fullmatch(re.escape(DEVELOPMENT_FEED_PREFIX + version) + r'-[0-9a-f]{12}/appcast\.xml', info.get('SUFeedURL', '')),
                'Bundle feed does not match development release channel')
    require(info.get('SURequireSignedFeed') is True and info.get('SUVerifyUpdateBeforeExtraction') is True,
            'Signed feed and verification before extraction are mandatory')
    require(info.get('SUPublicEDKey') == PUBLIC_KEY, 'Unexpected Sparkle public key')
    if channel == 'development':
        require(info.get('SUEnableAutomaticChecks') is False, 'Development builds must disable scheduled update checks')


def configure_bundle(app, channel):
    require(channel in {'stable', 'development'}, 'Unknown release channel')
    path = Path(app) / 'Contents/Info.plist'
    info = plistlib.loads(path.read_bytes())
    info['MacVisioReleaseChannel'] = channel
    if channel == 'stable':
        info['SUFeedURL'] = STABLE_FEED
    else:
        revision = subprocess.run(['git', 'rev-parse', '--short=12', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
        require(re.fullmatch(r'[0-9a-f]{12}', revision), 'Development feed requires a source revision')
        info['SUFeedURL'] = f"{DEVELOPMENT_FEED_PREFIX}{info['CFBundleShortVersionString']}-{revision}/appcast.xml"
    info['SUEnableAutomaticChecks'] = channel == 'stable'
    path.write_bytes(plistlib.dumps(info))


def validate_archive(package):
    """Bound untrusted release ZIPs before CRC checks, reads or ditto extraction."""
    entries = package.infolist()
    require(len(entries) <= 50000, 'Too many release ZIP entries')
    names = set()
    total = 0
    links = []
    for entry in entries:
        name = entry.filename
        parts = PurePosixPath(name).parts
        require(name and not name.startswith('/') and '\\' not in name and ':' not in name
                and '\x00' not in name and not any(p in {'.', '..', ''} for p in name.rstrip('/').split('/'))
                and parts[0] in {'MacVisio.app', '__MACOSX'},
                'Unsafe release ZIP path')
        require(name not in names, 'Duplicate release ZIP entry')
        names.add(name)
        require(not entry.flag_bits & 1, 'Encrypted release ZIP entry')
        require(entry.file_size <= 512 * 1024 * 1024, 'Release ZIP entry too large')
        total += entry.file_size
        require(total <= 2 * 1024 * 1024 * 1024, 'Release ZIP exceeds extracted size budget')
        mode = entry.external_attr >> 16
        kind = mode & 0o170000
        require(kind in {0, 0o040000, 0o100000, 0o120000}, 'Unsupported release ZIP entry type')
        if kind == 0o120000:
            require(entry.file_size <= 4096, 'Release ZIP symlink too long')
            target = package.read(entry).decode('utf-8')
            require(target and not target.startswith('/') and '\\' not in target and '\x00' not in target
                    and '..' not in PurePosixPath(target).parts,
                    'Unsafe release ZIP symlink')
            # Only downward relative links are needed by pinned Sparkle 2.10.0.
            # Disallow upward hops even through another symlink's target.
            require(parts[0] == 'MacVisio.app', 'Release ZIP symlink escapes bundle')
            links.append(name.rstrip('/'))
    for name in names:
        require(not any(name.startswith(link + '/') for link in links), 'Release ZIP writes through symlink')
    require('MacVisio.app/Contents/Info.plist' in names, 'Release ZIP has no application plist')
    require(package.getinfo('MacVisio.app/Contents/Info.plist').file_size <= 1024 * 1024,
            'Release application plist exceeds size budget')


def version_tuple(value):
    require(isinstance(value, str) and re.fullmatch(r'\d+(?:\.\d+){0,2}', value), 'Invalid minimum macOS version')
    parts = tuple(int(v) for v in value.split('.'))
    return parts + (0,) * (3 - len(parts))


def parse_macos_minimum(output):
    """Parse the macOS load-command floor for one Mach-O architecture."""
    current = None
    minimum = None
    platform = None
    for line in output.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] == 'cmd':
            current = words[1]
        elif current == 'LC_BUILD_VERSION' and len(words) == 2:
            if words[0] == 'platform':
                platform = words[1]
            elif words[0] == 'minos':
                minimum = words[1]
        elif current == 'LC_VERSION_MIN_MACOSX' and len(words) == 2 and words[0] == 'version':
            minimum, platform = words[1], 'macos'
    require(platform in {'1', 'MACOS', 'macos'} and minimum is not None, 'Mach-O has no supported macOS deployment command')
    version_tuple(minimum)
    return minimum


def bundle_platform(app, run=subprocess.run):
    app = Path(app)
    info = plistlib.loads((app / 'Contents/Info.plist').read_bytes())
    plist_minimum = info['LSMinimumSystemVersion']
    version_tuple(plist_minimum)
    binaries = []
    for path in sorted(app.rglob('*')):
        if path.is_symlink() or not path.is_file():
            continue
        with path.open('rb') as stream:
            if stream.read(4) not in MACH_MAGIC:
                continue
        archs = run(['lipo', '-archs', str(path)], capture_output=True, text=True, check=True).stdout.split()
        require(archs and set(archs) <= {'arm64', 'arm64e', 'x86_64'}, 'Unsupported Mach-O architecture')
        floors = {}
        for arch in sorted(archs):
            output = run(['otool', '-arch', arch, '-l', str(path)], capture_output=True, text=True, check=True).stdout
            floors[arch] = parse_macos_minimum(output)
        binaries.append({'path': path.relative_to(app).as_posix(), 'sha256': sha256(path), 'minimumMacOSByArchitecture': floors})
    require(binaries, 'Bundle has no Mach-O executables')
    architectures = set.intersection(*(set(v['minimumMacOSByArchitecture']) for v in binaries))
    require(architectures, 'Bundled binaries have no common architecture')
    minimums = {arch: max([plist_minimum] + [v['minimumMacOSByArchitecture'][arch] for v in binaries], key=version_tuple)
                for arch in sorted(architectures)}
    return {'architectures': sorted(architectures), 'minimumMacOSByArchitecture': minimums, 'binaries': binaries}


def validate_stable_manifest(manifest_path, candidate, verification):
    """Cross-check observations and retained acceptance against the exact archive."""
    manifest_path = Path(manifest_path)
    manifest = load_json(manifest_path)
    require(manifest.get('schemaVersion') == 1 and manifest.get('channel') == 'stable', 'Stable manifest schema/channel required')
    require(manifest.get('candidate') == candidate, 'Manifest does not describe this exact candidate')
    require(re.fullmatch(r'[0-9a-f]{40}', manifest.get('sourceCommit', '')) is not None, 'Manifest requires full source commit')
    for field in ('archiveSignatureVerified', 'feedSignatureVerified', 'bundleSignatureVerified', 'developerIDSigned', 'notarized', 'hardenedRuntime'):
        require(verification.get(field) is True, f'Stable release requires {field}')
    require(verification.get('teamID') == manifest.get('teamID') and isinstance(manifest.get('teamID'), str)
            and re.fullmatch(r'[A-Z0-9]{10}', manifest['teamID']), 'Stable Developer ID team mismatch')
    root = manifest_path.parent
    evidence = manifest.get('acceptance', {})
    require(set(evidence) == set(GATES), 'All stable acceptance gates are required')
    required_platforms = [
        {'architecture': arch, 'macOS': candidate['platform']['minimumMacOSByArchitecture'][arch]}
        for arch in candidate['platform']['architectures']
    ]
    declared_exceptions = manifest.get('qualificationExceptions', [])
    require(isinstance(declared_exceptions, list), 'Invalid release exceptions')
    approved = APPROVED_STABLE_EXCEPTIONS.get(candidate['sha256'], [])
    require(all(item in approved and item.get('version') == candidate['version']
                for item in declared_exceptions), 'Release exception is not owner-approved for this exact candidate')
    used_exceptions = []
    for gate, checks in GATES.items():
        record = load_json(checked_attachment(root, evidence[gate]))
        gate_exceptions = [item for item in declared_exceptions if item['gate'] == gate]
        expected_status = 'accepted_with_exception' if gate_exceptions else 'accepted'
        require(record.get('gate') == gate and record.get('status') == expected_status, f'{gate}: acceptance missing')
        require(record.get('candidateSHA256') == candidate['sha256'], f'{gate}: evidence belongs to another candidate')
        require(isinstance(record.get('reviewer'), str) and record['reviewer'].strip()
                and isinstance(record.get('recordedAt'), str) and record['recordedAt'].strip(), f'{gate}: reviewer/time required')
        require(record.get('platforms') == required_platforms, f'{gate}: exact declared platform evidence required')
        require(isinstance(record.get('checks'), dict), f'{gate}: required journeys are not accepted')
        for check in checks:
            exception = next((item for item in gate_exceptions if item['check'] == check), None)
            if exception:
                require(record['checks'].get(check) == 'waived_by_owner'
                        and record.get('exceptions', {}).get(check) == exception,
                        f'{gate}: approved exception must remain explicit, never passed')
                used_exceptions.append(exception)
            else:
                require(record['checks'].get(check) == 'passed', f'{gate}: required journeys are not accepted')
        artifacts = record.get('artifacts', [])
        require(isinstance(artifacts, list) and artifacts, f'{gate}: retained run artifacts required')
        for artifact in artifacts:
            checked_attachment(root, artifact)
    require(used_exceptions == declared_exceptions, 'Release exceptions are unused, duplicated or out of order')
    return manifest


def support_report(app):
    """Allowlist only: never reads drawings, preferences, environment, paths or logs."""
    info = plistlib.loads((Path(app) / 'Contents/Info.plist').read_bytes())
    return {'schemaVersion': 1, 'redaction': 'allowlisted-bundle-metadata-only',
            'application': {key: info[key] for key in ('CFBundleIdentifier', 'CFBundleShortVersionString', 'CFBundleVersion', 'LSMinimumSystemVersion', 'MacVisioReleaseChannel') if key in info}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['configure-bundle', 'platform', 'support'])
    parser.add_argument('app', type=Path)
    parser.add_argument('--channel', choices=['stable', 'development'], default='development')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.command == 'configure-bundle':
        configure_bundle(args.app, args.channel)
        return
    result = bundle_platform(args.app) if args.command == 'platform' else support_report(args.app)
    output = json.dumps(result, indent=2) + '\n'
    if args.output:
        args.output.write_text(output)
    else:
        print(output, end='')


if __name__ == '__main__':
    main()
